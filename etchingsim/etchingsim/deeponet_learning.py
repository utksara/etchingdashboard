def main():
    device = DEVICE
    print(f"Using device: {device}")

    train_ds = ParamCurveDataset(TRAIN_SAMPLES, curve_points=CURVE_POINTS)
    val_ds = ParamCurveDataset(VAL_SAMPLES, curve_points=CURVE_POINTS)

    # We train pointwise: create DataLoader that yields (params, x, y) as tensors
    def collate_fn(batch):
        p = np.stack([b[0] for b in batch], axis=0)
        x = np.stack([b[1] for b in batch], axis=0)
        y = np.stack([b[2] for b in batch], axis=0)
        return torch.from_numpy(p).float(), torch.from_numpy(x).float(), torch.from_numpy(y).float()

    train_loader = DataLoader(train_ds, batch_size=BATCH_SIZE, shuffle=True, collate_fn=collate_fn)

    model = DeepONet(NUM_PARAMS, BRANCH_OUTPUT_DIM, BRANCH_OUTPUT_DIM, BRANCH_HIDDEN, TRUNK_HIDDEN).to(device)
    opt = torch.optim.Adam(model.parameters(), lr=LR, weight_decay=1e-5)

    best_val = float('inf')
    history = {'train':[], 'val':[]}

    for epoch in range(1, EPOCHS + 1):
        train_loss = train_one_epoch(model, train_loader, opt, device)
        val_loss = evaluate(model, val_ds, device)
        history['train'].append(train_loss)
        history['val'].append(val_loss)

        if epoch % PRINT_EVERY == 0 or epoch == 1:
            print(f"Epoch {epoch}/{EPOCHS}  train_loss={train_loss:.6f}  val_loss={val_loss:.6f}")

        if val_loss < best_val:
            best_val = val_loss
            torch.save(model.state_dict(), "deeponet_best.pth")

    print("Training finished. Best val loss:", best_val)

    # plot losses
    plt.figure(figsize=(6,4))
    plt.plot(history['train'], label='train')
    plt.plot(history['val'], label='val')
    plt.yscale('log')
    plt.legend()
    plt.title('Loss curves')
    plt.show()

    # plot some reconstructions
    x_grid = np.linspace(0.0, 1.0, CURVE_POINTS)
    n_examples = 4
    idxs = np.random.choice(len(val_ds.params_all), size=n_examples, replace=False)
    model.load_state_dict(torch.load("deeponet_best.pth", map_location=device))

    plt.figure(figsize=(10, 6))
    for i, idx in enumerate(idxs, 1):
        p = val_ds.params_all[idx]
        y_true = val_ds.curves[idx]
        y_pred = reconstruct_curve(model, p, x_grid, device)
        plt.subplot(n_examples, 1, i)
        plt.plot(x_grid, y_true, label='true')
        plt.plot(x_grid, y_pred, '--', label='pred')
        plt.title(f'Example {i} params={np.round(p,2)}')
        if i == 1:
            plt.legend()
    plt.tight_layout()
    plt.show()


if __name__ == '__main__':
    main()
