def train_one_epoch(model, loader, opt, device):
    model.train()
    total_loss = 0.0
    for p_batch, x_batch, y_batch in loader:
        p_batch = p_batch.to(device)
        x_batch = x_batch.to(device)
        y_batch = y_batch.to(device)

        pred = model(p_batch, x_batch)
        loss = nn.functional.mse_loss(pred, y_batch)

        opt.zero_grad()
        loss.backward()
        opt.step()

        total_loss += loss.item() * p_batch.size(0)
    return total_loss / len(loader.dataset)


def evaluate(model, dataset: ParamCurveDataset, device, batch_size=1024) -> float:
    model.eval()
    loader = DataLoader(dataset, batch_size=batch_size, shuffle=False)
    tot = 0.0
    with torch.no_grad():
        for p_batch, x_batch, y_batch in loader:
            p_batch = p_batch.to(device)
            x_batch = x_batch.to(device)
            y_batch = y_batch.to(device)
            pred = model(p_batch, x_batch)
            loss = nn.functional.mse_loss(pred, y_batch, reduction='sum')
            tot += loss.item()
    return tot / len(loader.dataset)


def reconstruct_curve(model, params: np.ndarray, x_grid: np.ndarray, device) -> np.ndarray:
    model.eval()
    with torch.no_grad():
        P = params.astype(np.float32).reshape(1, -1)
        # evaluate for all x at once by repeating params
        X = x_grid.astype(np.float32).reshape(-1, 1)
        P_rep = np.repeat(P, X.shape[0], axis=0)
        p_t = torch.from_numpy(P_rep).to(device)
        x_t = torch.from_numpy(X).to(device)
        y_pred = model(p_t, x_t).cpu().numpy().ravel()
    return y_pred

